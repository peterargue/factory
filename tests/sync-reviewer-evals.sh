#!/usr/bin/env bash
# Writes each reviewer eval case's prompt.md from the reviewer prompt in
# .github/workflows/claude-review.yml, so the evals always test the prompt that ships.
#
#   tests/sync-reviewer-evals.sh           rewrite the prompt.md files
#   tests/sync-reviewer-evals.sh --check   exit 1 if any prompt.md is stale (CI)
#
# The workflow prompt is copied verbatim apart from its GitHub expressions, which are
# filled with the fixture's values. A short preface maps the three GitHub-only steps
# (gh pr view, inline comments, gh pr comment) onto files, because eval runs have no
# GitHub. Every other word is the shipped prompt.
set -euo pipefail

root=$(cd "$(dirname "$0")/.." && pwd)
workflow="$root/.github/workflows/claude-review.yml"
cases="$root/plugins/factory/evals/reviewer"
check=0
[ "${1:-}" = "--check" ] && check=1

# The block scalar after `prompt: |`, up to `claude_args:`, with its 12-space indent removed.
body=$(awk '
  /^          prompt: \|$/ { on = 1; next }
  on && /^          claude_args:/ { exit }
  on { sub(/^            /, ""); print }
' "$workflow")
[ -n "$body" ] || { echo "no reviewer prompt found in $workflow" >&2; exit 1; }

body=${body//'${{ github.repository }}'/acme/orders}
body=${body//'${{ github.event.pull_request.number }}'/42}
body=${body//'${{ inputs.review_notes }}'/}
if grep -q '\${{' <<<"$body"; then
  echo "reviewer prompt has a GitHub expression this script does not fill:" >&2
  grep -n '\${{' <<<"$body" >&2
  exit 1
fi

preface='EVAL ENVIRONMENT. This run has no GitHub access; the repository is checked out in the
working directory exactly as the workflow checks it out (HEAD is the merge commit, HEAD^1
the base). Where the instructions below say:

- `gh pr view 42`: read `PR.md` in the working directory instead. It holds the title, the
  description and the head SHA.
- post an inline comment with `mcp__github_inline_comment__create_inline_comment`: write
  the finding into `claude-review-summary.md` instead, under a heading `### <path>:<line>`.
- `gh pr comment 42 --body-file claude-review-summary.md`: skip it. Writing the file is the
  record.

Everything else applies exactly as written.
'

stale=0
for dir in "$cases"/*/; do
  [ -f "$dir/case.yaml" ] || continue
  want=$(printf -- '---\nmodel: claude-sonnet-5-5\nmax_turns: 40\ntimeout_seconds: 900\nallowed_tools: [Read, Write, Grep, Glob, TodoWrite, Bash]\n---\n\n<!-- Generated by tests/sync-reviewer-evals.sh from .github/workflows/claude-review.yml. Do not edit. -->\n\n%s\n%s\n' "$preface" "$body")
  if [ "$check" = 1 ]; then
    if [ "$(cat "$dir/prompt.md" 2>/dev/null)" != "$want" ]; then
      echo "stale: ${dir#"$root/"}prompt.md" >&2
      stale=1
    fi
  else
    printf '%s\n' "$want" > "$dir/prompt.md"
  fi
done
if [ "$stale" = 1 ]; then
  echo "run tests/sync-reviewer-evals.sh and commit the result" >&2
  exit 1
fi
